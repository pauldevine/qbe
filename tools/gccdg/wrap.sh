#!/bin/bash
# wrap.sh : select the runnable gcc.dg tests and wrap each in a PASS/ABORT
# driver -> $W/wrapped/<id>.c, plus $W/tests.txt (<id> <TAB> <source>).
#
# Selected: EDG "//type: rp" (runtime positive: self-checking, abort() on a
# wrong answer, return 0 on success) single-file tests.  Excluded, with the
# reason recorded in $W/excluded.txt:
#   multi-TU   //source_files
#   int32plus / lp64 / int128   dg-require-effective-target: needs a 32-bit int
#   envvar     dg-set-compiler-env-var (tests __DATE__ against an env var)
#   require    //require: (EDG configuration-dependent)
#   cpp-error  clang -E itself rejects it (#error, missing header, ...)
# A test's own 32-bit assumptions WITHOUT a dg marker are not filtered here;
# they show up as FAIL/ABORT in run.sh and are what baseline-<model>.txt is for.
#
# The driver prints exactly one GCCDG:<verdict> line: PASS (main returned 0
# or exit(0)), FAIL (main returned non-zero), ABORT (abort()), EXIT-NONZERO.
# It is placed BEFORE the body so build-example.sh's -Dmain=newlibc_test_main
# rename applies to it (the libstub-free crt0 entry), while the test's own
# main is renamed to gccdg_main via a later #define.  The forward declaration
# is K&R-style so it is compatible with any main() signature the test uses.
#
# The composite (shim + driver + test) is PRE-EXPANDED here with `clang -E`
# (a conforming preprocessor, the one build-micropython.sh uses) and the
# expanded text is what sweep.sh / build-example.sh compile.  macOS `cpp`,
# which build-example.sh runs on its source, is a TRADITIONAL preprocessor:
# a function-like macro invoked with a space before `(` -- `F (x)`, the GNU
# house style every gcc.dg test uses -- is NOT expanded there, which turned
# the libm shim and most test-local macros into parse errors / undefined
# symbols.  On the expanded text build-example's cpp pass is a no-op.
set -eu
. "$(dirname "$0")/common.sh"
[ -d "$R" ] || { echo "wrap: no $R -- run $TOOLS/fetch.sh first" >&2; exit 1; }
rm -rf "$WRAPPED"; mkdir -p "$WRAPPED/src"
cp "$TOOLS/gccshim.h" "$WRAPPED/src/"
: > "$W/tests.txt"; : > "$W/excluded.txt"
n=0
grep -rl -m1 '^//type: *rp' "$R" --include='*.c' | sort | while read -r src; do
	id="$(echo "${src#$R/}" | sed 's,/,__,g; s/\.sft\.c$//; s/\.c$//' | tr -c 'A-Za-z0-9_\n' '_')"   # nasm: '-' and '.' are operators in segment names
	why=""
	grep -q '^//source_files' "$src" && why="multi-TU"
	grep -q '^//require:' "$src" && why="require"
	grep -qE 'dg-require-effective-target +(\{ *)?(int32plus|lp64|int128)\b' "$src" && why="needs-32bit-int"
	grep -q 'dg-set-compiler-env-var' "$src" && why="envvar"
	if [ -n "$why" ]; then printf '%s\t%s\t%s\n' "$id" "$why" "$src" >> "$W/excluded.txt"; continue; fi
	{
		echo "/* generated by tools/gccdg/wrap.sh from ${src#$EDG/} -- do not edit */"
		echo '#include "gccshim.h"'
		echo '#include <stdio.h>'
		echo '#include <stdlib.h>'
		echo 'void gccdg_abort(void) { printf("GCCDG:ABORT\n"); exit(1); }'
		echo 'void gccdg_exit(int c) { printf(c ? "GCCDG:EXIT-NONZERO\n" : "GCCDG:PASS\n"); exit(c); }'
		echo 'int gccdg_main();'
		echo 'int main(void) { int r = gccdg_main(); printf(r ? "GCCDG:FAIL\n" : "GCCDG:PASS\n"); return r; }'
		echo '#define abort gccdg_abort'
		echo '#define exit gccdg_exit'
		echo '#define main gccdg_main'
		echo "#include \"$src\""
	} > "$WRAPPED/src/$PFX$id.c"
	if clang -E -P -nostdinc -isysroot/var/empty -DDOS -D__TURBOC__ \
			"-I$Q/minic/include" "-I$WRAPPED/src" "$WRAPPED/src/$PFX$id.c" \
			2>"$WRAPPED/src/$PFX$id.cpp.err" | tr -d '\r\032' > "$WRAPPED/$PFX$id.c"; then
		printf '%s\t%s\n' "$id" "$src" >> "$W/tests.txt"
	else
		rm -f "$WRAPPED/$PFX$id.c"
		printf '%s\t%s\t%s\n' "$id" "cpp-error" "$src" >> "$W/excluded.txt"
	fi
done
echo "wrap: $(wc -l < "$W/tests.txt" | tr -d ' ') wrapped, $(wc -l < "$W/excluded.txt" | tr -d ' ') excluded ($(cut -f2 "$W/excluded.txt" | sort | uniq -c | awk '{printf "%s %s, ", $2, $1}' | sed 's/, $//'))"
